package Patterns;

public class AlphabetPatterns
{
    public static void main(String[] args)
    {
        int n = 5;

        for(int i=1;i<=n;i++,System.out.println())
        {
            //int count = 1;
            char c = 'A';
            for(int j=1;j<=i;j++)
            {
                System.out.print(c + " ");
                //count++;
                c++;
            }

        }
    }
}
